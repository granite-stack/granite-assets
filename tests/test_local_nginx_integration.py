# ---------------------------------------------------------------------------
# No-secret fallback (unit-style, no Docker needed)
# ---------------------------------------------------------------------------


def test_private_url_without_secret_raises(tmp_path: Path) -> None:
    """When secure_link_secret is None, URL methods raise
    AssetAccessNotSupportedError."""
    cfg = LocalNginxAssetRepositoryConfig(
        storage_path=str(tmp_path),
        base_url="http://localhost/assets",
        secure_link_secret=None,
        create_directories=True,
    )
    repo = LocalNginxAssetRepository(cfg)
    repo.save(
        AssetSaveRequest(
            key="priv.txt",
            source=b"x",
            content_type="text/plain",
            visibility=AssetVisibility.PRIVATE,
        )
    )
    with pytest.raises(AssetAccessNotSupportedError):
        repo.build_download_url("priv.txt")

    with pytest.raises(AssetAccessNotSupportedError):
        repo.resolve_access("priv.txt")
